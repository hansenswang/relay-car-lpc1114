/**
 * @file    bsp_oled.c
 * @brief   HS96L03W2C03 128x64 monochrome OLED, bit-banged.
 *
 * The module is a standard SSD1306-class controller in 4-wire SPI mode:
 *   SCL  -> P0_6   (clock)
 *   SDA  -> P0_7   (data)
 *   RES  -> P1_0   (reset, active low)
 *   DC   -> P1_1   (0 = command, 1 = data)
 *   CS   -> P1_2   (chip select, active low)
 *
 * Bit-banging rather than the SSP peripheral was a deliberate choice.  The
 * SSP block is shared with the NRF24L01 and the two have incompatible
 * configurations (the radio needs a different clock phase), so multiplexing
 * them means re-initialising the peripheral on every switch — which costs
 * more than the handful of microseconds a bit-banged write takes.  The
 * display refreshes at 10 Hz, so the bus is idle 99.9 % of the time anyway.
 */

#include "LPC11xx.h"
#include "bsp_oled.h"
#include <stdarg.h>
#include <stdio.h>

/* ---- pin macros ------------------------------------------------------- */
#define OLED_SCL    (1UL << 6)      /* P0_6 */
#define OLED_SDA    (1UL << 7)      /* P0_7 */
#define OLED_RES    (1UL << 0)      /* P1_0 */
#define OLED_DC     (1UL << 1)      /* P1_1 */
#define OLED_CS     (1UL << 2)      /* P1_2 */

#define SCL_H()   (LPC_GPIO0->DATA |=  OLED_SCL)
#define SCL_L()   (LPC_GPIO0->DATA &= ~OLED_SCL)
#define SDA_H()   (LPC_GPIO0->DATA |=  OLED_SDA)
#define SDA_L()   (LPC_GPIO0->DATA &= ~OLED_SDA)
#define RES_H()   (LPC_GPIO1->DATA |=  OLED_RES)
#define RES_L()   (LPC_GPIO1->DATA &= ~OLED_RES)
#define DC_H()    (LPC_GPIO1->DATA |=  OLED_DC)
#define DC_L()    (LPC_GPIO1->DATA &= ~OLED_DC)
#define CS_H()    (LPC_GPIO1->DATA |=  OLED_CS)
#define CS_L()    (LPC_GPIO1->DATA &= ~OLED_CS)

/* A 6x8 ASCII cell means 21 columns and 8 rows on a 128x64 panel. */
#define OLED_COLS   21
#define OLED_ROWS   8


/* ---- low-level transfers --------------------------------------------- */

static void oled_wr_byte(uint8_t data, uint8_t is_data)
{
    uint8_t i;

    if (is_data) { DC_H(); } else { DC_L(); }
    CS_L();

    for (i = 0; i < 8; i++)
    {
        SCL_L();
        if (data & 0x80) { SDA_H(); } else { SDA_L(); }
        data <<= 1;
        SCL_H();            /* data is clocked on the rising edge */
    }

    CS_H();
}

static void oled_wr_cmd(uint8_t cmd)  { oled_wr_byte(cmd, 0); }
static void oled_wr_data(uint8_t dat) { oled_wr_byte(dat, 1); }

static void oled_set_cursor(uint8_t page, uint8_t col)
{
    oled_wr_cmd(0xB0 | (page & 0x07));                  /* page address  */
    oled_wr_cmd(0x10 | ((col >> 4) & 0x0F));            /* column high 4 */
    oled_wr_cmd(0x00 | (col & 0x0F));                   /* column low  4 */
}

/* ---- public API ------------------------------------------------------- */

void bsp_oled_init(void)
{
    LPC_GPIO0->DIR |= OLED_SCL | OLED_SDA;
    LPC_GPIO1->DIR |= OLED_RES | OLED_DC | OLED_CS;

    CS_H();
    RES_L();
    delay_ms(20);
    RES_H();
    delay_ms(20);

    oled_wr_cmd(0xAE);      /* display off                        */
    oled_wr_cmd(0xD5);      /* clock divide / oscillator          */
    oled_wr_cmd(0x80);
    oled_wr_cmd(0xA8);      /* multiplex ratio                    */
    oled_wr_cmd(0x3F);      /* 1/64 duty                          */
    oled_wr_cmd(0xD3);      /* display offset                     */
    oled_wr_cmd(0x00);
    oled_wr_cmd(0x40);      /* start line = 0                     */
    oled_wr_cmd(0x8D);      /* charge pump                         */
    oled_wr_cmd(0x14);      /* enable                             */
    oled_wr_cmd(0x20);      /* memory addressing mode             */
    oled_wr_cmd(0x00);      /* horizontal                         */
    oled_wr_cmd(0xA1);      /* segment remap                      */
    oled_wr_cmd(0xC8);      /* COM scan direction remapped        */
    oled_wr_cmd(0xDA);      /* COM pins hardware configuration    */
    oled_wr_cmd(0x12);
    oled_wr_cmd(0x81);      /* contrast                           */
    oled_wr_cmd(0xCF);
    oled_wr_cmd(0xD9);      /* pre-charge period                  */
    oled_wr_cmd(0xF1);
    oled_wr_cmd(0xDB);      /* VCOMH deselect level               */
    oled_wr_cmd(0x40);
    oled_wr_cmd(0xA4);      /* resume from RAM                    */
    oled_wr_cmd(0xA6);      /* normal (not inverted)              */
    oled_wr_cmd(0xAF);      /* display on                         */
}

void bsp_oled_clear(void)
{
    uint8_t page, col;

    for (page = 0; page < OLED_ROWS; page++)
    {
        oled_set_cursor(page, 0);
        for (col = 0; col < 128; col++)
        {
            oled_wr_data(0x00);
        }
    }
}

void bsp_oled_show_string(uint8_t row, uint8_t col, const char *str)
{
    uint8_t i;

    if (row < 1 || row > OLED_ROWS) { return; }

    oled_set_cursor((uint8_t)(row - 1), (uint8_t)((col - 1) * 6));

    while (*str && col <= OLED_COLS)
    {
        if (*str < 0x20 || *str > 0x7E)
        {
            /* Anything outside the stored range — including the lead bytes
             * of a GB2312 sequence — is drawn as a blank cell rather than
             * as a garbage glyph.  The UI is ASCII-only by design. */
            for (i = 0; i < 6; i++) { oled_wr_data(0x00); }
        }
        else
        {
            const uint8_t *g = font6x8[(uint8_t)(*str) - 0x20];
            for (i = 0; i < 6; i++) { oled_wr_data(g[i]); }
        }
        str++;
        col++;
    }
}

void bsp_oled_printf(uint8_t row, uint8_t col, const char *fmt, ...)
{
    char    buf[24];
    va_list ap;

    va_start(ap, fmt);
    /* vsnprintf is deliberately chosen over sprintf: a malformed format
     * string must not be able to walk past the end of a stack buffer on a
     * device with 8 KiB of RAM and no memory protection. */
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    bsp_oled_show_string(row, col, buf);
}
